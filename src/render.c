void draw_model_with_light(Asset_Model *model, V3f position, Mat3 rotation, Light light)
{
    // Mat4 pers = perspective(NEAR, FAR, ASPECT_RATIO, FOV);
    Mat4 view = camera_matrix(renderer.camera);
    for (s32 i = 0; i < arrlen(model->vertices); i += 3)
    {
        Vertex v1 = model->vertices[i];
        Vertex v2 = model->vertices[i + 1];
        Vertex v3 = model->vertices[i + 2];

        V3f p1 = v3f_mul_mat3(v1.position, rotation);
        V3f p2 = v3f_mul_mat3(v2.position, rotation);
        V3f p3 = v3f_mul_mat3(v3.position, rotation);

        V3f n1 = v3f_mul_mat3(v1.normal, rotation);
        V3f n2 = v3f_mul_mat3(v2.normal, rotation);
        V3f n3 = v3f_mul_mat3(v3.normal, rotation);

        p1.z = -p1.z;
        p2.z = -p2.z;
        p3.z = -p3.z;
        p1 = v3f_add(p1, position);
        p2 = v3f_add(p2, position);
        p3 = v3f_add(p3, position);

        p1 = v3f_translate_by_mat4(p1, view);
        p2 = v3f_translate_by_mat4(p2, view);
        p3 = v3f_translate_by_mat4(p3, view);

        if (p1.z >= NEAR && p2.z >= NEAR && p3.z >= NEAR)
        {
            Color t1;
            Color t2;
            Color t3;
            t1 = COLOR_WHITE;
            t2 = COLOR_WHITE;
            t3 = COLOR_WHITE;

            Color c1 = simple_reflection(model->mtl, light.position, p1, n1, light.color, t1);
            Color c2 = simple_reflection(model->mtl, light.position, p2, n2, light.color, t2);
            Color c3 = simple_reflection(model->mtl, light.position, p3, n3, light.color, t3);

            Color colors[3] = {c1, c2, c3};
            V3f uvs[3] = {v1.uv, v2.uv, v3.uv};
            renderer_push_triangle(
                p1,
                p2,
                p3,
                colors,
                uvs,
                model->mtl->diffuse_texture,
                0);
        }
    }
}

Color simple_reflection(SimpleMtl *mtl, V3f light_pos, V3f v, V3f n, V3f light_color, Color object_color)
{
    if (mtl == NULL)
        return object_color;
    V3f norm = v3f_normalize(n);
    V3f light_dir = v3f_normalize(v3f_sub(v, light_pos));

    f32 diff = fmaxf(v3f_dot(norm, light_dir), 0.0f);

    V3f obj = {
        object_color.r / 255.0,
        object_color.g / 255.0,
        object_color.b / 255.0,
    };
    V3f diffuse = v3f_scale(light_color, diff);
    V3f result = v3f_mul(v3f_add(diffuse, mtl->ambient), obj);

    Color res = (Color){
        .r = (u8)(fminf(result.x, 1.0f) * 255),
        .g = (u8)(fminf(result.y, 1.0f) * 255),
        .b = (u8)(fminf(result.z, 1.0f) * 255),
        .a = 255,
    };
    return res;
}

