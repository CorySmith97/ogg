typedef struct {
    s32 tile_x, tile_y;
    SizeArray tri_idx;
} TileBin;

typedef struct
{
    pthread_t thread;
    TileBin *bin;
    s32 active;
} Worker;

TileBin triangle_bins[(GAME_WIDTH / TILE_W) * (GAME_HEIGHT / TILE_H)];
TriangleArray *triangles;
Worker workers[NUM_THREADS];
pthread_mutex_t queue_mutex = PTHREAD_MUTEX_INITIALIZER;
pthread_cond_t queue_cond = PTHREAD_COND_INITIALIZER;
pthread_cond_t done_cond = PTHREAD_COND_INITIALIZER;

TileBin *work_queue[TILE_COUNT];
s32 queue_head = 0;
s32 queue_tail = 0;
s32 jobs_remaining = 0;
s32 pool_running = 1;

// TODO The multithread approach was generated by claude. It needs to be revisited.
void *worker_thread(void *arg)
{
    UNUSED(arg);
    while (1)
    {
        pthread_mutex_lock(&queue_mutex);

        while (queue_head == queue_tail && pool_running)
            pthread_cond_wait(&queue_cond, &queue_mutex);

        if (!pool_running && queue_head == queue_tail)
        {
            pthread_mutex_unlock(&queue_mutex);
            return NULL;
        }

        // Grab bin pos32er AND increment while still holding the lock
        TileBin *bin = work_queue[queue_head % TILE_COUNT];
        queue_head++;

        // Snapshot the triangle indices we need to process
        // so we can release the lock before doing pixel work
        size_t len = bin->tri_idx.len;

        // TODO this needs to be a fixed buffer of some kind.
        size_t local_idx[len]; // VLA, or heap alloc if len could be huge
        memcpy(local_idx, bin->tri_idx.data, len * sizeof(size_t));
        bin->tri_idx.len = 0; // clear while locked, before workers
                                    // can re-queue this bin next frame

        pthread_mutex_unlock(&queue_mutex);

        for (size_t i = 0; i < len; i++)
        {
            renderer_draw_triangle(
                bin->tile_x * TILE_W,
                bin->tile_y * TILE_H,
                triangles->data[local_idx[i]] // triangles[] is read-only during dispatch
            );
        }

        pthread_mutex_lock(&queue_mutex);
        jobs_remaining--;
        if (jobs_remaining == 0)
            pthread_cond_signal(&done_cond);
        pthread_mutex_unlock(&queue_mutex);
    }
}

void render_init(void)
{

    triangles = malloc(sizeof(TriangleArray));
    s32 initial = 1000;
    triangles->capacity = initial;
    log_debug("Triangle data pointer %p", triangles->data);
    triangles->data = malloc(sizeof(Triangle) * initial);
    triangles->len = 0;
    log_debug("Triangle data pointer %p", triangles->data);
    renderer.width = GAME_WIDTH;
    renderer.height = GAME_HEIGHT;
    for (size_t i = 0; i < TILE_COUNT; i++)
    {
        s32 x = i % (GAME_WIDTH / TILE_W);
        s32 y = i / (GAME_WIDTH / TILE_W);
        triangle_bins[i].tile_x = x;
        triangle_bins[i].tile_y = y;
        triangle_bins[i].tri_idx.data = malloc(initial * sizeof(size_t));
        triangle_bins[i].tri_idx.capacity = initial;
    }

    for (s32 i = 0; i < NUM_THREADS; i++)
        pthread_create(&workers[i].thread, NULL, worker_thread, NULL);

}

void render_shutdown(void)
{
    pthread_mutex_lock(&queue_mutex);
    pool_running = 0;
    pthread_cond_broadcast(&queue_cond);
    pthread_mutex_unlock(&queue_mutex);

    for (s32 i = 0; i < NUM_THREADS; i++)
        pthread_join(workers[i].thread, NULL);
}


void change_camera(void)
{
    Camera temp_camera;
    temp_camera = renderer.swap_camera;
    renderer.swap_camera = renderer.camera;
    renderer.camera = temp_camera;
}

void renderer_flush(void)
{
    //log_info("Triangles rendererd %zd", triangles->len);
    // enqueue all non-empty bins
    pthread_mutex_lock(&queue_mutex);
    for (s32 i = 0; i < TILE_COUNT; i++)
    {
        if (triangle_bins[i].tri_idx.len > 0)
        {
            work_queue[queue_tail % TILE_COUNT] = &triangle_bins[i];
            queue_tail++;
            jobs_remaining++;
        }
    }
    pthread_cond_broadcast(&queue_cond); // wake all workers

    // wait for all tiles to finish
    while (jobs_remaining > 0)
        pthread_cond_wait(&done_cond, &queue_mutex);
    pthread_mutex_unlock(&queue_mutex);

    // clear triangle list for next frame
    triangles->len = 0;
}


#define PIXEL_INDEX(x, y) ((size_t)(x) + (size_t)(y) * (size_t)renderer.width)

static inline void set_pixel(s32 x, s32 y, Color src)
{
    if (x < 0 || y < 0 || x >= renderer.width || y >= renderer.height)
        return;

    size_t idx = PIXEL_INDEX(x, y);
    Color dst = (Color)renderer.pixels[idx];

    if (src.a == 0)
        return;

    if (src.a == 255) {
        renderer.pixels[idx] = src.rgba;
        return;
    }

    Color out = alpha_blend(src, dst);
    renderer.pixels[idx] = out.rgba;
}

void set_verline(u32 x, u32 start, u32 end, Color color)
{
    for (u32 i = start; i < end; i++)
    {
        set_pixel(x, i, color);
    }
}

void set_line(V2i v, V2i u, Color color)
{
    bool steep = false;
    if (abs(v.x - v.y) < abs(u.x - u.y))
    {
        V2i temp;
        temp = v;
        v = u;
        u = temp;
        steep = true;
    }

    s32 y = v.y;
    s32 ierror = 0;
    for (s32 x = v.x; x < u.x; x++)
    {
        if (steep)
            set_pixel(y, x, color);
        else
            set_pixel(x, y, color);
        ierror += abs(u.y - v.y);
        if (ierror > u.x - v.x)
        {
            y += u.y > v.y ? 1 : -1;
            ierror -= 2 * (u.x - v.x);
        }
    }
}

bool check_bounds(V2i v1, V2i v2, V2i v3)
{
    if (v1.x < 0 || v1.x > GAME_WIDTH || v2.x < 0 || v2.x > GAME_WIDTH || v3.x < 0 || v3.x > GAME_WIDTH || v1.y < 0 || v1.y > GAME_HEIGHT || v2.y < 0 || v2.y > GAME_HEIGHT || v3.y < 0 || v3.y > GAME_HEIGHT)
        return false;

    return true;
}

void set_triangle(V2i v1, V2i v2, V2i v3, Color color)
{
    AABBi rec = {
        v2i(min(v1.x, min(v2.x, v3.x)), min(v1.y, min(v2.y, v3.y))),
        v2i(max(v1.x, max(v2.x, v3.x)), max(v1.y, max(v2.y, v3.y))),
    };
    V3f bary;

    for (s32 x = rec.min.x; x < rec.max.x; x++)
    {
        for (s32 y = rec.min.y; y < rec.max.y; y++)
        {
            if (barycentric(v1, v2, v3, v2i(x, y), &bary))
            {
                set_pixel((u32)x, (u32)y, color);
            }
        }
    }
}

void set_triangle_multicolor(V2i v1, V2i v2, V2i v3, Color c1, Color c2, Color c3)
{
    AABBi rec = {
        v2i(min(v1.x, min(v2.x, v3.x)), min(v1.y, min(v2.y, v3.y))),
        v2i(max(v1.x, max(v2.x, v3.x)), max(v1.y, max(v2.y, v3.y))),
    };
    V3f bary;

    for (s32 x = rec.min.x; x < rec.max.x; x++)
    {
        for (s32 y = rec.min.y; y < rec.max.y; y++)
        {
            if (barycentric(v1, v2, v3, v2i(x, y), &bary))
            {
                Color color = color_add(color_add(color_scale(c1, bary.x), color_scale(c2, bary.y)), color_scale(c3, bary.z));
                set_pixel((u32)x, (u32)y, color);
            }
        }
    }
}

void renderer_push_triangle(V3f v1, V3f v2, V3f v3, Color color[3], V3f uvs[3], Texture *t, u32 flags)
{
    V2i pos1;
    V2i pos2;
    V2i pos3;
    if (!FlagExists(flags, TRIANGLE_TWO_D))
    {
        pos1 = to_screen(project(v1));
        pos2 = to_screen(project(v2));
        pos3 = to_screen(project(v3));
    }
    else
    {
        pos1 = v2i(v1.x, v1.y);
        pos2 = v2i(v2.x, v2.y);
        pos3 = v2i(v3.x, v3.y);
    }
    /* if (!check_bounds(pos1, pos2, pos3))
        return; */

    AABBi rec = {
        v2i(min(pos1.x, min(pos2.x, pos3.x)), min(pos1.y, min(pos2.y, pos3.y))),
        v2i(max(pos1.x, max(pos2.x, pos3.x)), max(pos1.y, max(pos2.y, pos3.y))),
    };

    size_t t_minx = max(0, floor(rec.min.x / TILE_W));
    size_t t_maxx = min((GAME_WIDTH / TILE_W) - 1, floor(rec.max.x > 0 ? rec.max.x : 0 / TILE_W));
    size_t t_miny = max(0, floor(rec.min.y / TILE_H));
    size_t t_maxy = min((GAME_HEIGHT / TILE_H) - 1, floor(rec.max.y > 0 ? rec.max.y : 0 / TILE_H));

    Triangle triangle = {
        .vertices = {v1, v2, v3},
        .uvs = {uvs[0], uvs[1], uvs[2]},
        .colors = {color[0], color[1], color[2]},
        .texture = t,
        .flags = flags,
    };

    array_push(triangles, triangle);
    size_t idx = triangles->len - 1;

    for (size_t j = t_miny; j <= t_maxy; j++)
    {
        for (size_t i = t_minx; i <= t_maxx; i++)
        {
            size_t index = i + j * COL_GAME_WIDTH;
            if (index < TILE_COUNT)
                array_push(&triangle_bins[index].tri_idx, idx);
        }
    }
}

